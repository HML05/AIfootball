def _pos_raw(p) -> str:
    """归一化空值: None / NaN / 空串 统一视为空"""
    if p is None:
        return ""
    s = str(p).strip()
    return "" if s.lower() in ("", "nan", "none", "null") else s


def pos_zh(p) -> str:
    """位置显示名: 中文态给中文, 英文态回退英文原文; 空值统一 '—'"""
    raw = _pos_raw(p)
    if not raw:
        return "—"
    return t(POS_ZH.get(raw, raw), raw)


def pos_group(p) -> str:
    """位置大组代码 GK/DF/MF/FW(语言无关, 供计数与分组); 未收录归 'OT'"""
    return POS_GRP.get(_pos_raw(p), "OT")


def pos_group_label(code) -> str:
    """大组代码的当前语言可读名"""
    return t(POS_GRP_ZH.get(code, code), POS_GRP_EN.get(code))
