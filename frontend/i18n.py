def lang_selector():
    """侧边栏语言切换"""
    choice = st.selectbox("Language / 语言", ["中文", "English"],
                          index=0 if st.session_state.get("lang", "zh") == "zh" else 1,
                          key="lang_choice")
    st.session_state["lang"] = "zh" if choice == "中文" else "en"


def lang() -> str:
    return st.session_state.get("lang", "zh")


def t(zh: str, en: str = None) -> str:
    """返回当前语言文案; 未提供 en 时查内置词条表"""
    if lang() == "zh":
        return zh
    return en if en is not None else EN.get(zh, zh)


